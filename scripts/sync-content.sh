#!/usr/bin/env bash
# Sync content/spec and content/skills from their source repos and open a PR.
# The sources are canonical; the copies in content/ are generated. Uses your gh login.
# The Sync content workflow runs this daily with SYNC_BRANCH=content/sync, so one pull request
# stays open and is updated in place instead of a new one each day. While that pull request is
# open, new syncs are committed on top of it, so commits added by hand (a changelog entry) stay.
set -euo pipefail
cd "$(dirname "$0")/.."
git fetch -q origin main
BRANCH="${SYNC_BRANCH:-content/sync-$(date +%Y%m%d-%H%M)}"
OPEN_PR=false
if [ "$(gh pr view "$BRANCH" --json state -q .state 2>/dev/null)" = OPEN ]; then OPEN_PR=true; fi
if $OPEN_PR; then
  git fetch -q origin "$BRANCH"
  git switch -q -C "$BRANCH" "origin/$BRANCH"
else
  git switch -q -C "$BRANCH" origin/main
fi
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
for d in spec skills; do
  gh repo clone "devrel-md/$d" "$TMP/$d" -- -q --depth 1
  sha=$(git -C "$TMP/$d" rev-parse HEAD); if [ "$d" = spec ]; then SPEC_SHA=$sha; else SKILLS_SHA=$sha; fi
  find "content/$d" -mindepth 1 ! -name SYNCED-FROM.md -delete
  rsync -a --exclude .git --exclude .gitignore "$TMP/$d/" "content/$d/"
done
printf '{\n  "spec": {"repo": "devrel-md/spec", "commit": "%s"},\n  "skills": {"repo": "devrel-md/skills", "commit": "%s"}\n}\n' "$SPEC_SHA" "$SKILLS_SHA" > content/SOURCES.json
if git diff --quiet && git diff --cached --quiet && [ -z "$(git status --porcelain)" ]; then
  echo "Content already up to date."; git switch -q -; git branch -q -D "$BRANCH"; exit 0
fi
git add -A content
git commit -qm "Sync spec and skills content (spec ${SPEC_SHA:0:7}, skills ${SKILLS_SHA:0:7})"
if $OPEN_PR; then
  git push -q -u origin "$BRANCH"
  echo "Updated the open pull request on $BRANCH."; exit 0
fi
# No open pull request: any leftover branch of that name is stale, so replace it.
git push -q --force -u origin "$BRANCH"
gh pr create --base main --head "$BRANCH" --title "Sync spec and skills content" \
  --body "Generated by scripts/sync-content.sh. Sources: devrel-md/spec@${SPEC_SHA:0:7}, devrel-md/skills@${SKILLS_SHA:0:7}. Review the preview before merging, and add a \`content/site/changelog.md\` entry if the change is visible to users."
